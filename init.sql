DROP TABLE IF EXISTS auto_plan_report;

CREATE TABLE auto_plan_report (
                                  id BIGINT GENERATED BY DEFAULT AS IDENTITY NOT NULL,
                                  report_id VARCHAR(100) NOT NULL,
                                  report_name VARCHAR(125) NOT NULL,
                                  plan_id VARCHAR(100) NOT NULL,
                                  rank_id BIGINT NOT NULL DEFAULT 0,
                                  plan_name VARCHAR(255) NOT NULL,
                                  team_id VARCHAR(100) NOT NULL,
                                  task_type INTEGER NOT NULL DEFAULT 0,
                                  task_mode INTEGER NOT NULL DEFAULT 0,
                                  control_mode SMALLINT NOT NULL DEFAULT 0,
                                  scene_run_order SMALLINT NOT NULL DEFAULT 1,
                                  test_case_run_order SMALLINT NOT NULL DEFAULT 1,
                                  run_duration_time BIGINT NOT NULL DEFAULT 0,
                                  status SMALLINT NOT NULL DEFAULT 1,
                                  run_user_id VARCHAR(100) NOT NULL DEFAULT '0',
                                  remark TEXT NOT NULL,
                                  created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
                                  updated_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
