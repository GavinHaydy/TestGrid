DROP TABLE IF EXISTS auto_plan;

CREATE TABLE auto_plan (
                           id BIGINT GENERATED BY DEFAULT AS IDENTITY NOT NULL,
                           plan_id VARCHAR(100) NOT NULL,
                           rank_id BIGINT NOT NULL DEFAULT 0,
                           team_id VARCHAR(100) NOT NULL,
                           plan_name VARCHAR(255) NOT NULL,
                           task_type SMALLINT NOT NULL DEFAULT 1,
                           status SMALLINT NOT NULL DEFAULT 1,
                           create_user_id VARCHAR(100) NOT NULL,
                           run_user_id VARCHAR(100) NOT NULL,
                           remark TEXT,
                           run_count BIGINT NOT NULL DEFAULT 0,
                           created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
                           updated_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
                           deleted_at TIMESTAMP DEFAULT NULL,

                           PRIMARY KEY (id),
                           CONSTRAINT chk_auto_plan_run_count CHECK (run_count >= 0)
);

CREATE INDEX idx_plan_id ON auto_plan (plan_id);
CREATE INDEX idx_team_id ON auto_plan (team_id);

COMMENT ON TABLE auto_plan IS '自动化测试-计划表';

COMMENT ON COLUMN auto_plan.id IS '主键';
COMMENT ON COLUMN auto_plan.plan_id IS '计划ID';
COMMENT ON COLUMN auto_plan.rank_id IS '序号ID';
COMMENT ON COLUMN auto_plan.team_id IS '团队ID';
COMMENT ON COLUMN auto_plan.plan_name IS '计划名称';
COMMENT ON COLUMN auto_plan.task_type IS '计划类型：1-普通任务，2-定时任务';
COMMENT ON COLUMN auto_plan.status IS '计划状态1:未开始,2:进行中';
COMMENT ON COLUMN auto_plan.create_user_id IS '创建人id';
COMMENT ON COLUMN auto_plan.run_user_id IS '运行人id';
COMMENT ON COLUMN auto_plan.remark IS '备注';
COMMENT ON COLUMN auto_plan.run_count IS '运行次数';
COMMENT ON COLUMN auto_plan.created_at IS '创建时间';
COMMENT ON COLUMN auto_plan.updated_at IS '更新时间';
COMMENT ON COLUMN auto_plan.deleted_at IS '删除时间';

